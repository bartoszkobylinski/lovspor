class TestSplice:
    BLOCK = f"{STATUS_START}\nnew\n{STATUS_END}"

    def test_replaces_only_the_text_between_the_markers(self) -> None:
        readme = f"# lovverk\n\nprose\n\n{STATUS_START}\nold\n{STATUS_END}\n\n## Next\n\nmore\n"

        assert splice(readme, self.BLOCK) == (
            f"# lovverk\n\nprose\n\n{STATUS_START}\nnew\n{STATUS_END}\n\n## Next\n\nmore\n"
        )

    def test_without_markers_inserts_before_the_first_second_level_heading(self) -> None:
        readme = "# lovverk\n\nintro\n\n## What this is\n\ntext\n\n## Other\n"

        assert splice(readme, self.BLOCK) == (
            f"# lovverk\n\nintro\n\n{self.BLOCK}\n\n## What this is\n\ntext\n\n## Other\n"
        )

    def test_without_markers_or_headings_appends_at_the_end(self) -> None:
        assert splice("# lovverk\n\nintro\n", self.BLOCK) == f"# lovverk\n\nintro\n\n{self.BLOCK}\n"

    def test_a_deeper_heading_is_not_an_insertion_point(self) -> None:
        readme = "# lovverk\n\n### Deep\n\n## Top\n"

        assert splice(readme, self.BLOCK) == f"# lovverk\n\n### Deep\n\n{self.BLOCK}\n\n## Top\n"

    def test_splicing_twice_is_idempotent(self) -> None:
        readme = "# lovverk\n\nintro\n\n## A\n"
        once = splice(readme, self.BLOCK)

        assert splice(once, self.BLOCK) == once

    @pytest.mark.parametrize(
        "readme",
        [
            f"{STATUS_START}\nno end\n",
            f"no start\n{STATUS_END}\n",
            f"{STATUS_END}\nswapped\n{STATUS_START}\n",
            f"{STATUS_START}\n{STATUS_END}\n{STATUS_START}\n{STATUS_END}\n",
        ],
    )
    def test_broken_markers_are_refused(self, readme: str) -> None:
        with pytest.raises(ReadmeBlockError, match="corpus-status"):
            splice(readme, self.BLOCK)


class TestRefreshReadme:
    def test_writes_the_block_and_keeps_the_prose(self, tmp_path: Path) -> None:
        readme = "# lovverk\n\nHand-written intro.\n\n## Usage\n\nHand-written usage.\n"
        corpus = _corpus(tmp_path, _central(2, 1), _local({"5025": 1}), readme)

        assert refresh_readme(corpus) is ReadmeOutcome.WRITTEN

        text = (corpus / README_NAME).read_text(encoding="utf-8")
        assert text.startswith("# lovverk\n\nHand-written intro.\n\n" + STATUS_START)
        assert text.endswith(STATUS_END + "\n\n## Usage\n\nHand-written usage.\n")
        assert "| `forskrifter/` | 1 |" in text

    def test_a_second_refresh_over_the_same_manifests_writes_nothing(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(2, 1), _local({"5025": 1}), "# lovverk\n")
        refresh_readme(corpus)
        before = (corpus / README_NAME).stat().st_mtime_ns

        assert refresh_readme(corpus) is ReadmeOutcome.UNCHANGED
        assert (corpus / README_NAME).stat().st_mtime_ns == before

    def test_a_checkout_without_a_readme_gets_none(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(1, 1), None, None)

        assert refresh_readme(corpus) is ReadmeOutcome.ABSENT
        assert not (corpus / README_NAME).exists()

    def test_broken_markers_leave_the_readme_untouched(self, tmp_path: Path) -> None:
        readme = f"# lovverk\n\n{STATUS_START}\nhalf a block\n"
        corpus = _corpus(tmp_path, _central(1, 1), None, readme)

        assert refresh_readme(corpus) is ReadmeOutcome.MALFORMED
        assert (corpus / README_NAME).read_text(encoding="utf-8") == readme
