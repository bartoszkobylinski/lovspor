CENTRAL_AT = "2026-10-17T08:29:12.672271Z"
LOCAL_AT = "2026-10-20T17:00:04.618698Z"


def _central(lover: int, forskrifter: int, removed: int = 0) -> dict[str, Any]:
    documents: dict[str, Any] = {}
    for n in range(lover):
        documents[f"nl-{n}"] = {"status": "current", "source_dataset": "gjeldende-lover"}
    for n in range(forskrifter):
        documents[f"sf-{n}"] = {
            "status": "current",
            "source_dataset": "gjeldende-sentrale-forskrifter",
        }
    for n in range(removed):
        documents[f"nl-removed-{n}"] = {"status": "removed", "source_dataset": "gjeldende-lover"}
    return {"documents": documents, "generated_at": CENTRAL_AT, "version": 1}


def _local(per_authority: dict[str, int], generated_at: str | None = LOCAL_AT) -> dict[str, Any]:
    documents: dict[str, Any] = {}
    for authority, count in per_authority.items():
        for n in range(count):
            documents[f"lk-{authority}-{n}"] = {
                "status": "current",
                "source_dataset": "lokale-forskrifter",
                "authority_id": authority,
                "authority_type": "fylkeskommune" if len(authority) == 2 else "kommune",
            }
    documents["lk-withdrawn"] = {
        "status": "removed",
        "source_dataset": "lokale-forskrifter",
        "authority_id": "0301",
        "authority_type": "kommune",
    }
    return {"documents": documents, "generated_at": generated_at, "version": 1}


def _corpus(
    tmp_path: Path, central: dict[str, Any], local: dict[str, Any] | None, readme: str | None
) -> Path:
    (tmp_path / "manifest.json").write_text(json.dumps(central), encoding="utf-8")
    if local is not None:
        (tmp_path / "lokale-forskrifter").mkdir()
        local_path = tmp_path / "lokale-forskrifter" / "manifest.json"
        local_path.write_text(json.dumps(local), encoding="utf-8")
    if readme is not None:
        (tmp_path / README_NAME).write_text(readme, encoding="utf-8")
    return tmp_path


EXPECTED_BLOCK = f"""{STATUS_START}
## Corpus status

Generated by `lovspor` from the manifests on every sync and promotion; anything between these markers is overwritten.

| Dataset | Current documents | Published under | Manifest generated |
| --- | ---: | --- | --- |
| `lover/` | 754 | Lovdata public data, NLOD 2.0 | 2026-10-17 |
| `forskrifter/` | 5,126 | Lovdata public data, NLOD 2.0 | 2026-10-17 |
| `lokale-forskrifter/` | 26 | åndsverkloven § 14 | 2026-10-20 |

`lover/` and `forskrifter/` together hold 5,880 current documents; removed documents stay in `manifest.json` as tombstones and are not counted.

`lokale-forskrifter/` holds 26 local regulations from 3 authorities, published on the basis of åndsverkloven § 14 and not asserted to be in force: fylkeskommune 46 (1), kommune 1848 (1), kommune 5025 (24).
{STATUS_END}"""  # noqa: E501


class TestRenderBlock:
    def test_renders_counts_bases_and_manifest_dates(self, tmp_path: Path) -> None:
        corpus = _corpus(
            tmp_path, _central(754, 5126, removed=3), _local({"5025": 24, "1848": 1, "46": 1}), None
        )

        assert render_block(read_status(corpus)) == EXPECTED_BLOCK

    def test_an_empty_local_dataset_says_it_holds_no_regulation(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(1, 0), _local({}, generated_at=None), None)

        block = render_block(read_status(corpus))

        assert "| `lokale-forskrifter/` | 0 | åndsverkloven § 14 | not yet |" in block
        assert "`lokale-forskrifter/` holds no current local regulation." in block
        assert "`lover/` and `forskrifter/` together hold 1 current document;" in block

    def test_one_regulation_from_one_authority_is_singular(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(0, 0), _local({"1848": 1}), None)

        block = render_block(read_status(corpus))

        assert "holds 1 local regulation from 1 authority," in block

    def test_a_checkout_without_the_local_dataset_has_no_local_lines(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(2, 0), None, None)

        block = render_block(read_status(corpus))

        assert "lokale-forskrifter" not in block
        assert "| `lover/` | 2 |" in block

    def test_no_line_about_local_regulations_mentions_nlod(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(3, 3), _local({"5025": 2}), None)

        local_lines = [
            line
            for line in render_block(read_status(corpus)).splitlines()
            if "lokale-forskrifter" in line
        ]

        assert len(local_lines) == 2
        assert not any("nlod" in line.lower() for line in local_lines)

    def test_same_manifests_render_byte_identical_whatever_their_key_order(
        self, tmp_path: Path
    ) -> None:
        central = _central(5, 4, removed=1)
        reversed_central = {**central, "documents": dict(reversed(central["documents"].items()))}
        (tmp_path / "a").mkdir()
        (tmp_path / "b").mkdir()
        first = _corpus(tmp_path / "a", central, _local({"5025": 2, "1848": 1}), None)
        second = _corpus(tmp_path / "b", reversed_central, _local({"1848": 1, "5025": 2}), None)

        assert render_block(read_status(first)) == render_block(read_status(second))


