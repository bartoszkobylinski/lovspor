class TestSplice:
    BLOCK = f"{STATUS_START}\nnew\n{STATUS_END}"

    @pytest.mark.parametrize("indent", ["", " ", "  ", "   "])
    def test_standalone_markers_allow_up_to_three_spaces_and_trailing_whitespace(
        self, indent: str
    ) -> None:
        prefix = "# lovverk\n\nHåndskrevet tekst.\n\n"
        suffix = "\n\n## Bruk\n"
        readme = f"{prefix}{indent}{STATUS_START} \t\nold\n{indent}{STATUS_END}\t{suffix}"

        assert splice(readme, self.BLOCK) == prefix + self.BLOCK + suffix

    def test_replaces_only_the_text_between_the_markers(self) -> None:
        readme = f"# lovverk\n\nprose\n\n{STATUS_START}\nold\n{STATUS_END}\n\n## Next\n\nmore\n"

        assert splice(readme, self.BLOCK) == (
            f"# lovverk\n\nprose\n\n{STATUS_START}\nnew\n{STATUS_END}\n\n## Next\n\nmore\n"
        )

    def test_without_markers_inserts_before_the_first_second_level_heading(self) -> None:
        readme = "# lovverk\n\nintro\n\n## What this is\n\ntext\n\n## Other\n"

        assert splice(readme, self.BLOCK) == (
            f"# lovverk\n\nintro\n\n{self.BLOCK}\n\n## What this is\n\ntext\n\n## Other\n"
        )

    def test_without_markers_or_headings_appends_at_the_end(self) -> None:
        assert splice("# lovverk\n\nintro\n", self.BLOCK) == f"# lovverk\n\nintro\n\n{self.BLOCK}\n"

    def test_a_deeper_heading_is_not_an_insertion_point(self) -> None:
        readme = "# lovverk\n\n### Deep\n\n## Top\n"

        assert splice(readme, self.BLOCK) == f"# lovverk\n\n### Deep\n\n{self.BLOCK}\n\n## Top\n"

    def test_splicing_twice_is_idempotent(self) -> None:
        readme = "# lovverk\n\nintro\n\n## A\n"
        once = splice(readme, self.BLOCK)

        assert splice(once, self.BLOCK) == once

    @pytest.mark.parametrize(
        "readme",
        [
            f"{STATUS_START}\nno end\n",
            f"no start\n{STATUS_END}\n",
            f"{STATUS_END}\nswapped\n{STATUS_START}\n",
            f"{STATUS_START}\n{STATUS_END}\n{STATUS_START}\n{STATUS_END}\n",
        ],
    )
    def test_broken_markers_are_refused(self, readme: str) -> None:
        with pytest.raises(ReadmeBlockError, match="corpus-status"):
            splice(readme, self.BLOCK)

    @pytest.mark.parametrize(
        ("prose", "appended"),
        [
            ("# lovverk\n\nintro\n\n\n\n", f"{BLOCK}\n"),
            ("# lovverk\n\nintro\n\n", f"{BLOCK}\n"),
            ("# lovverk\n\nintro\n", f"\n{BLOCK}\n"),
            ("# lovverk\n\nintro", f"\n\n{BLOCK}\n"),
            ("\n\n\n", f"{BLOCK}\n"),
            ("", f"{BLOCK}\n"),
        ],
    )
    def test_appending_keeps_every_byte_of_the_prose_before_it(
        self, prose: str, appended: str
    ) -> None:
        assert splice(prose, self.BLOCK) == prose + appended

    def test_appending_to_crlf_prose_keeps_it_and_uses_crlf(self) -> None:
        prose = "# lovverk\r\n\r\nintro"

        assert splice(prose, self.BLOCK) == (
            f"{prose}\r\n\r\n{STATUS_START}\r\nnew\r\n{STATUS_END}\r\n"
        )

    def test_inserting_into_crlf_prose_keeps_it_and_uses_crlf(self) -> None:
        readme = "# lovverk\r\n\r\nintro\r\n\r\n## A\r\n"

        assert splice(readme, self.BLOCK) == (
            f"# lovverk\r\n\r\nintro\r\n\r\n{STATUS_START}\r\nnew\r\n{STATUS_END}\r\n\r\n## A\r\n"
        )

    def test_crlf_splicing_twice_is_idempotent(self) -> None:
        once = splice("# lovverk\r\n\r\n## A\r\n", self.BLOCK)

        assert splice(once, self.BLOCK) == once

    @pytest.mark.parametrize("tail", ["", "\n", "\n\n\n"])
    def test_a_block_at_the_end_of_the_file_keeps_what_follows_its_end_marker(
        self, tail: str
    ) -> None:
        readme = f"# lovverk\n\n{STATUS_START}\nold\n{STATUS_END}{tail}"

        assert splice(readme, self.BLOCK) == f"# lovverk\n\n{self.BLOCK}{tail}"

    def test_markers_and_headings_inside_a_code_fence_are_prose(self) -> None:
        fenced = f"```markdown\n{STATUS_START}\nexample\n{STATUS_END}\n## Not a heading\n```\n"
        readme = f"# lovverk\n\n{fenced}\n## Real\n"

        assert splice(readme, self.BLOCK) == f"# lovverk\n\n{fenced}\n{self.BLOCK}\n\n## Real\n"

    def test_a_fenced_example_beside_the_real_block_is_left_alone(self) -> None:
        fenced = f"~~~\n{STATUS_START}\nexample\n{STATUS_END}\n~~~\n"
        readme = f"{fenced}\n{STATUS_START}\nold\n{STATUS_END}\n"

        assert splice(readme, self.BLOCK) == f"{fenced}\n{self.BLOCK}\n"

    @pytest.mark.parametrize(
        ("opening", "inner", "closing"),
        [
            ("````markdown", "```", "````"),
            ("```markdown", "~~~", "```"),
            ("~~~~", "~~~", "~~~~~"),
            ("```", "```js", "   ```"),
            ("~~~", "```", "~~~ \t"),
        ],
        ids=[
            "shorter-run-does-not-close",
            "other-character-does-not-close",
            "longer-run-closes",
            "info-string-does-not-close-indent-3-closes",
            "trailing-whitespace-closes",
        ],
    )
    def test_only_a_commonmark_closing_fence_ends_the_code(
        self, opening: str, inner: str, closing: str
    ) -> None:
        fenced = (
            f"{opening}\n{inner}\n{STATUS_START}\nexample\n"
            f"{STATUS_END}\n## Example heading\n{closing}\n"
        )
        readme = f"# lovverk\n\n{fenced}\n## Real\n"

        assert splice(readme, self.BLOCK) == f"# lovverk\n\n{fenced}\n{self.BLOCK}\n\n## Real\n"

    def test_an_unclosed_fence_runs_to_the_end_of_the_document(self) -> None:
        readme = f"# lovverk\n\n```\n{STATUS_START}\nexample\n{STATUS_END}\n## Fenced\n"

        assert splice(readme, self.BLOCK) == f"{readme}\n{self.BLOCK}\n"

    @pytest.mark.parametrize(
        "not_a_fence",
        ["    ```", "``", "~~", "```a`b"],
        ids=["indented-4", "two-backticks", "two-tildes", "backtick-in-info"],
    )
    def test_a_line_that_cannot_open_a_fence_leaves_the_markers_live(
        self, not_a_fence: str
    ) -> None:
        readme = f"{not_a_fence}\n\n{STATUS_START}\nold\n{STATUS_END}\n"

        assert splice(readme, self.BLOCK) == f"{not_a_fence}\n\n{self.BLOCK}\n"

    def test_a_fence_indented_up_to_three_spaces_still_opens(self) -> None:
        fenced = f"   ~~~\n{STATUS_START}\n{STATUS_END}\n~~~\n"

        assert splice(fenced, self.BLOCK) == f"{fenced}\n{self.BLOCK}\n"

    def test_a_marker_indented_four_spaces_is_code_not_a_marker(self) -> None:
        readme = f"# lovverk\n\n    {STATUS_START}\n    {STATUS_END}\n"

        assert splice(readme, self.BLOCK) == f"{readme}\n{self.BLOCK}\n"

    def test_a_marker_quoted_inside_a_prose_line_is_not_a_marker(self) -> None:
        readme = f"# lovverk\n\nThe block starts at `{STATUS_START}`.\n"

        assert splice(readme, self.BLOCK) == f"{readme}\n{self.BLOCK}\n"


class TestRefreshReadme:
    def test_manifest_changes_refresh_counts_dates_and_authorities(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(2, 1), _local({"0301": 1, "5025": 1}), "# lovverk\n")
        assert refresh_readme(corpus) is ReadmeOutcome.WRITTEN
        central = _central(1, 2, removed=1)
        central["generated_at"] = "2026-10-23T12:00:00Z"
        local = _local({"5025": 2}, generated_at="2026-10-24T12:00:00Z")
        (corpus / "manifest.json").write_text(json.dumps(central), encoding="utf-8")
        (corpus / "lokale-forskrifter" / "manifest.json").write_text(
            json.dumps(local), encoding="utf-8"
        )

        assert refresh_readme(corpus) is ReadmeOutcome.WRITTEN

        text = (corpus / README_NAME).read_text(encoding="utf-8")
        assert "| `lover/` | 1 | Lovdata public data, NLOD 2.0 | 2026-10-23 |" in text
        assert "| `forskrifter/` | 2 | Lovdata public data, NLOD 2.0 | 2026-10-23 |" in text
        assert "| `lokale-forskrifter/` | 2 | åndsverkloven § 14 | 2026-10-24 |" in text
        assert "together hold 3 current documents;" in text
        assert "holds 2 local regulations from 1 authority," in text
        assert "kommune 5025 (2)." in text
        assert "0301" not in text
        assert refresh_readme(corpus) is ReadmeOutcome.UNCHANGED

    @pytest.mark.parametrize("manifest_name", ["manifest.json", "lokale-forskrifter/manifest.json"])
    @pytest.mark.parametrize(
        "invalid",
        [b"{not json", b"\xff", b'{"documents": {"broken": {"status": "current"}}}'],
        ids=["malformed-json", "invalid-utf8", "missing-dataset"],
    )
    def test_invalid_manifest_raises_without_overwriting_readme(
        self, tmp_path: Path, manifest_name: str, invalid: bytes
    ) -> None:
        corpus = _corpus(tmp_path, _central(1, 1), _local({"0301": 1}), "# lovverk\n")
        assert refresh_readme(corpus) is ReadmeOutcome.WRITTEN
        before = (corpus / README_NAME).read_bytes()
        (corpus / manifest_name).write_bytes(invalid)

        with pytest.raises(ParseError, match="manifest.json"):
            refresh_readme(corpus)

        assert (corpus / README_NAME).read_bytes() == before

    def test_absent_readme_needs_no_manifests(self, tmp_path: Path) -> None:
        assert refresh_readme(tmp_path) is ReadmeOutcome.ABSENT
        assert list(tmp_path.iterdir()) == []

    def test_writes_the_block_and_keeps_the_prose(self, tmp_path: Path) -> None:
        readme = "# lovverk\n\nHand-written intro.\n\n## Usage\n\nHand-written usage.\n"
        corpus = _corpus(tmp_path, _central(2, 1), _local({"5025": 1}), readme)

        assert refresh_readme(corpus) is ReadmeOutcome.WRITTEN

        text = (corpus / README_NAME).read_text(encoding="utf-8")
        assert text.startswith("# lovverk\n\nHand-written intro.\n\n" + STATUS_START)
        assert text.endswith(STATUS_END + "\n\n## Usage\n\nHand-written usage.\n")
        assert "| `forskrifter/` | 1 |" in text

    def test_prose_with_crlf_newlines_keeps_its_bytes(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(2, 1), None, None)
        prefix = "# lovverk\r\n\r\nHåndskrevet innledning.\r\n\r\n".encode()
        suffix = "\r\n\r\n## Bruk\r\n\r\nHåndskrevet tekst.\r\n".encode()
        path = corpus / README_NAME
        path.write_bytes(prefix + f"{STATUS_START}\r\nold\r\n{STATUS_END}".encode() + suffix)

        assert refresh_readme(corpus) is ReadmeOutcome.WRITTEN

        updated = path.read_bytes()
        assert updated.split(STATUS_START.encode(), 1)[0] == prefix
        assert updated.split(STATUS_END.encode(), 1)[1] == suffix

    def test_a_second_refresh_over_the_same_manifests_writes_nothing(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(2, 1), _local({"5025": 1}), "# lovverk\n")
        refresh_readme(corpus)
        before = (corpus / README_NAME).stat().st_mtime_ns

        assert refresh_readme(corpus) is ReadmeOutcome.UNCHANGED
        assert (corpus / README_NAME).stat().st_mtime_ns == before

    def test_a_checkout_without_a_readme_gets_none(self, tmp_path: Path) -> None:
        corpus = _corpus(tmp_path, _central(1, 1), None, None)

        assert refresh_readme(corpus) is ReadmeOutcome.ABSENT
        assert not (corpus / README_NAME).exists()

    def test_broken_markers_leave_the_readme_untouched(self, tmp_path: Path) -> None:
        readme = f"# lovverk\n\n{STATUS_START}\nhalf a block\n"
        corpus = _corpus(tmp_path, _central(1, 1), None, readme)

        assert refresh_readme(corpus) is ReadmeOutcome.MALFORMED
        assert (corpus / README_NAME).read_text(encoding="utf-8") == readme


