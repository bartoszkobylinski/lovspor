"""The generated corpus-status block of the ``lovverk`` README (#661).

The README is hand-written prose except for one block between
:data:`STATUS_START` and :data:`STATUS_END`, which the engine owns: the
current-document count of each dataset, read from the two manifests, and the
state of the local dataset. ``lovspor sync`` and every ``lovspor promote``
command that writes into the corpus re-render it from the manifests they have
just written, so the counts move with the corpus rather than with whoever
last edited the prose. Nothing outside the markers is ever changed.

Deterministic: the only dates in the block are the manifests' own
``generated_at`` — never the clock — and authorities are listed by type, then
KLASS code, so the same
manifests render the same bytes and a run that changes no manifest leaves the
README untouched.

A README with no block yet gets one before its first second-level heading (at
the end when it has none): that is how the block first reaches ``lovverk``.
A README with a broken marker pair is left as it is and reported. A checkout
with no README gets none; the README is the corpus's own file.

The local dataset is published on the basis of åndsverkloven § 14 (ADR-0016);
the lines that describe it name only that basis.
"""

from __future__ import annotations

from collections import Counter
from datetime import date, datetime
from enum import StrEnum
from pathlib import Path

from pydantic import BaseModel, ConfigDict, ValidationError

from lovspor.atomic_io import atomic_write_text
from lovspor.errors import ParseError, ReadmeBlockError

README_NAME = "README.md"
STATUS_START = "<!-- lovspor:corpus-status:start -->"
STATUS_END = "<!-- lovspor:corpus-status:end -->"

_MANIFEST = "manifest.json"
_LOCAL_DATASET = "lokale-forskrifter"
_CENTRAL = (("lover/", "gjeldende-lover"), ("forskrifter/", "gjeldende-sentrale-forskrifter"))
_LOVDATA_BASIS = "Lovdata public data, NLOD 2.0"
_LOCAL_BASIS = "åndsverkloven § 14"
_HEADER = (
    "## Corpus status",
    "",
    "Generated by `lovspor` from the manifests on every sync and promotion; "
    "anything between these markers is overwritten.",
    "",
    "| Dataset | Current documents | Published under | Manifest generated |",
    "| --- | ---: | --- | --- |",
)


class ReadmeOutcome(StrEnum):
    """What one refresh did to the README."""

    WRITTEN = "written"
    UNCHANGED = "unchanged"
    ABSENT = "absent"
    MALFORMED = "malformed"


class _Entry(BaseModel):
    model_config = ConfigDict(frozen=True, extra="ignore")

    status: str
    source_dataset: str
    authority_id: str | None = None
    authority_type: str | None = None


class _ManifestView(BaseModel):
    """The fields of either manifest the block is counted from."""

    model_config = ConfigDict(frozen=True, extra="ignore")

    generated_at: datetime | None = None
    documents: dict[str, _Entry]


class DatasetStatus(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    directory: str
    current: int
    generated_on: date | None


class AuthorityCount(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    authority_id: str
    authority_type: str
    current: int


class CorpusStatus(BaseModel):
    """Everything the block shows, read from the manifests on disk."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    central: tuple[DatasetStatus, ...]
    local: DatasetStatus | None
    authorities: tuple[AuthorityCount, ...]


def read_status(repo: Path) -> CorpusStatus:
    """The corpus status of the checkout at ``repo``; the local part only if it has the dataset."""
    central = _read_view(repo / _MANIFEST)
    local_path = repo / _LOCAL_DATASET / _MANIFEST
    local = _read_view(local_path) if local_path.is_file() else None
    return CorpusStatus(
        central=tuple(_dataset(central, directory, name) for directory, name in _CENTRAL),
        local=None if local is None else _dataset(local, f"{_LOCAL_DATASET}/", _LOCAL_DATASET),
        authorities=() if local is None else _authorities(local),
    )


def _read_view(path: Path) -> _ManifestView:
    try:
        return _ManifestView.model_validate_json(path.read_bytes())
    except (OSError, ValidationError) as exc:
        msg = f"{path} does not read as a manifest: {exc}"
        raise ParseError(msg) from exc


def _dataset(view: _ManifestView, directory: str, source_dataset: str) -> DatasetStatus:
    current = sum(
        1
        for entry in view.documents.values()
        if entry.status == "current" and entry.source_dataset == source_dataset
    )
    generated = None if view.generated_at is None else view.generated_at.date()
    return DatasetStatus(directory=directory, current=current, generated_on=generated)


def _authorities(view: _ManifestView) -> tuple[AuthorityCount, ...]:
    counts = Counter(
        (entry.authority_type or "", entry.authority_id or "")
        for entry in view.documents.values()
        if entry.status == "current"
    )
    return tuple(
        AuthorityCount(authority_id=authority_id, authority_type=kind, current=count)
        for (kind, authority_id), count in sorted(counts.items())
    )


def render_block(status: CorpusStatus) -> str:
    """The block, markers included, with no trailing newline."""
    rows = [_row(dataset, _LOVDATA_BASIS) for dataset in status.central]
    paragraphs = [_central_total(status)]
    if status.local is not None:
        rows.append(_row(status.local, _LOCAL_BASIS))
        paragraphs.append(_local_state(status.local, status.authorities))
    body = [*_HEADER, *rows, *(line for text in paragraphs for line in ("", text))]
    return "\n".join([STATUS_START, *body, STATUS_END])


def _row(dataset: DatasetStatus, basis: str) -> str:
    generated = "not yet" if dataset.generated_on is None else dataset.generated_on.isoformat()
    return f"| `{dataset.directory}` | {dataset.current:,} | {basis} | {generated} |"


def _central_total(status: CorpusStatus) -> str:
    total = sum(dataset.current for dataset in status.central)
    return (
        f"`lover/` and `forskrifter/` together hold {_count(total, 'current document')}; "
        "removed documents stay in `manifest.json` as tombstones and are not counted."
    )


def _local_state(local: DatasetStatus, authorities: tuple[AuthorityCount, ...]) -> str:
    if local.current == 0:
        return f"`{local.directory}` holds no current local regulation."
    listed = ", ".join(f"{a.authority_type} {a.authority_id} ({a.current:,})" for a in authorities)
    return (
        f"`{local.directory}` holds {_count(local.current, 'local regulation')} from "
        f"{_count(len(authorities), 'authority', 'authorities')}, published on the basis of "
        f"{_LOCAL_BASIS} and not asserted to be in force: {listed}."
    )


def _count(number: int, singular: str, plural: str | None = None) -> str:
    noun = singular if number == 1 else (plural or f"{singular}s")
    return f"{number:,} {noun}"


def splice(readme: str, block: str) -> str:
    """``readme`` with ``block`` in place of its generated block, or inserted if it has none."""
    starts, ends = readme.count(STATUS_START), readme.count(STATUS_END)
    if starts == ends == 0:
        return _insert(readme, block)
    head, _, rest = readme.partition(STATUS_START)
    if starts != 1 or ends != 1 or STATUS_END not in rest:
        msg = f"{README_NAME} needs one corpus-status start marker followed by one end marker"
        raise ReadmeBlockError(msg)
    return head + block + rest.partition(STATUS_END)[2]


def _insert(readme: str, block: str) -> str:
    lines = readme.splitlines(keepends=True)
    for index, line in enumerate(lines):
        if line.startswith("## "):
            return "".join(lines[:index]) + block + "\n\n" + "".join(lines[index:])
    return readme.rstrip("\n") + "\n\n" + block + "\n"


def refresh_readme(repo: Path) -> ReadmeOutcome:
    """Re-render the README's block at ``repo`` from its manifests; write only a change."""
    path = repo / README_NAME
    if not path.is_file():
        return ReadmeOutcome.ABSENT
    current = path.read_text(encoding="utf-8")
    try:
        updated = splice(current, render_block(read_status(repo)))
    except ReadmeBlockError:
        return ReadmeOutcome.MALFORMED
    if updated == current:
        return ReadmeOutcome.UNCHANGED
    atomic_write_text(path, updated)
    return ReadmeOutcome.WRITTEN
